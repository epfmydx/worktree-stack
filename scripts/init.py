#!/usr/bin/env python3
"""Generate private local configuration; never start services or modify host trust."""
from pathlib import Path
import os
import secrets
import shlex
import subprocess

root = Path(__file__).resolve().parents[1]
env = root / ".env"
if not env.exists():
    values = {}
    for line in (root / ".env.example").read_text().splitlines():
        if line and not line.startswith("#"):
            key, value = line.split("=", 1)
            values[key] = value
    for key in ("MYSQL_ROOT_PASSWORD", "POSTGRES_PASSWORD", "REDIS_PASSWORD", "DASHBOARD_PASSWORD"):
        values[key] = secrets.token_hex(24)
    values["HOST_CONTAINERS_PATH"] = str(root)
    fd = os.open(env, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as out:
        out.write("# Private local configuration; generated by make init.\n")
        out.writelines(f"{key}={shlex.quote(value)}\n" for key, value in values.items())
    print("Created private .env with fresh local credentials.")
else:
    print("Keeping existing .env.")
subprocess.run([str(root / "scripts/stack.sh"), "certs-init"], check=True)
print("Local files ready. Next: make base; make infra; make sample-setup p=sample-laravel")
print("Certificate trust and host DNS are separate opt-in steps; see docs/operations/setup.md.")
